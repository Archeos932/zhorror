/* vitrine : un couloir et les six pieces a theme autour (captures --shot chambre, sdb..., et tests) */
static void charger_vitrine(void) {
    unsigned keep = rng;
    rng = 1998;
    carte_vider(44, 26);
    creuser(1, 12, 42, 13);
    carteDepart = v3(2.5f, 0, 12.5f);
    int zs[7] = { ZONE_CHAMBRE, ZONE_SDB, ZONE_ENFANT, ZONE_CUISINE, ZONE_RESERVE, ZONE_NOE, ZONE_CAMERAS };
    placer_pieces(zs, 7);
    carte_distances((int)carteDepart.x, (int)carteDepart.z);
    placer_cameras();
    placer_neons();
    rng = keep;
}
static int piece_de_zone(int z) { for (int i = 0; i < npieces; i++) if (pieces[i].zone == z) return i; return -1; }

